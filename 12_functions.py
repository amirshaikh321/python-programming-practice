# function

def addition(num1,num2):
    return num1 + num2
def substraction(num1,num2):
    return num1 - num2
def multiply(num1,num2):
    return num1 * num2
def division(num1,num2):
    return num1 / num2
print(addition(10,10))
print(substraction(10,5))
print(multiply(10,5))
print(division(10,2))
